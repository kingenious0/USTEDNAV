CREATE TABLE IF NOT EXISTS public.analytics_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL,
    device_id TEXT,
    session_id TEXT,
    device_os TEXT,
    is_pwa BOOLEAN DEFAULT FALSE,
    path TEXT,
    screen_size TEXT,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index for high-speed queries & dashboards
CREATE INDEX IF NOT EXISTS idx_analytics_event_name ON public.analytics_events (event_name);
CREATE INDEX IF NOT EXISTS idx_analytics_created_at ON public.analytics_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_analytics_device_id ON public.analytics_events (device_id);

-- Enable Row Level Security (RLS)
ALTER TABLE public.analytics_events ENABLE ROW LEVEL SECURITY;

-- Allow anonymous visitors to INSERT telemetry events (write-only)
CREATE POLICY "Allow anonymous inserts to analytics_events"
    ON public.analytics_events
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- Allow reading analytics for dashboard/service role
CREATE POLICY "Allow read for service role and anon"
    ON public.analytics_events
    FOR SELECT
    TO anon, authenticated
    USING (true);

